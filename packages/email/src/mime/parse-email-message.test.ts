import { readFile } from 'node:fs/promises';
import { describe, expect, it } from 'vitest';
import type { EmailSummary } from '../email-message.types';
import { parseEmailMessage } from './parse-email-message';

const summary: EmailSummary = {
  ref: 'opaque-reference',
  from: [{ name: 'Envelope sender', address: 'sender@example.com' }],
  subject: 'Envelope subject',
  receivedAt: new Date('2026-09-09T06:00:00.000Z'),
  isRead: false,
  sizeBytes: 500,
};

describe('parseEmailMessage', () => {
  it('maps plain text headers and content into package-owned fields', async () => {
    const message = await parseEmailMessage(
      await fixture('plain-text.eml'),
      summary,
    );

    expect(message).toMatchObject({
      ...summary,
      messageId: '<plain-1@example.com>',
      inReplyTo: [],
      references: [],
      to: [{ name: 'Studio', address: 'studio@example.com' }],
      cc: [{ name: 'Producer', address: 'producer@example.com' }],
      replyTo: [{ name: null, address: 'replies@example.com' }],
      sentAt: new Date('2026-09-08T07:30:00.000Z'),
      text: 'Could you quote a two-day photo shoot?\n',
      html: null,
    });
  });

  it('returns both alternatives for a multipart message', async () => {
    const message = await parseEmailMessage(
      await fixture('html-and-text.eml'),
      summary,
    );

    expect(message.text).toBe('The campaign starts next month.\n');
    expect(message.html).toContain('<strong>next month</strong>');
  });

  it('uses nulls and empty address arrays for missing optional fields', async () => {
    const message = await parseEmailMessage(
      await fixture('missing-fields.eml'),
      summary,
    );

    expect(message).toMatchObject({
      messageId: null,
      inReplyTo: [],
      references: [],
      to: [],
      cc: [],
      replyTo: [],
      sentAt: null,
      html: null,
    });
  });

  it('normalizes valid single and multiple thread identifiers', async () => {
    const message = await parseEmailMessage(
      sourceWithHeaders([
        'Message-ID: (generated by provider) <current@example.com>',
        'In-Reply-To: <previous@example.com>',
        'References: <root@example.com> <previous@example.com>',
      ]),
      summary,
    );

    expect(message).toMatchObject({
      messageId: '<current@example.com>',
      inReplyTo: ['<previous@example.com>'],
      references: ['<root@example.com>', '<previous@example.com>'],
    });
  });

  it('keeps each valid identifier from a multiple-value thread header', async () => {
    const message = await parseEmailMessage(
      sourceWithHeaders([
        'In-Reply-To: <first@example.com> <second@example.com>',
        'References: legacy text <valid@example.com> <invalid> <also@valid.example>',
      ]),
      summary,
    );

    expect(message.inReplyTo).toEqual([
      '<first@example.com>',
      '<second@example.com>',
    ]);
    expect(message.references).toEqual([
      '<valid@example.com>',
      '<also@valid.example>',
    ]);
  });

  it('ignores identifiers inside nested and escaped comments', async () => {
    const message = await parseEmailMessage(
      sourceWithHeaders([
        String.raw`In-Reply-To: (unrelated (nested <nested@example.com>) escaped \) <fake@example.com>) <real@example.com>`,
        String.raw`References: <root@example.com> (ignore <comment@example.com>) <real@example.com>`,
      ]),
      summary,
    );

    expect(message.inReplyTo).toEqual(['<real@example.com>']);
    expect(message.references).toEqual([
      '<root@example.com>',
      '<real@example.com>',
    ]);
  });

  it('rejects malformed message and thread identifiers', async () => {
    const message = await parseEmailMessage(
      sourceWithHeaders([
        'Message-ID: <first@example.com> <second@example.com>',
        'In-Reply-To: <missing-domain@> not-an-id',
        'References: <white space@example.com> <missing-at-sign>',
      ]),
      summary,
    );

    expect(message).toMatchObject({
      messageId: null,
      inReplyTo: [],
      references: [],
    });
  });
});

function fixture(name: string): Promise<Buffer> {
  return readFile(new URL(`../../test-fixtures/${name}`, import.meta.url));
}

function sourceWithHeaders(headers: string[]): Buffer {
  return Buffer.from(
    `${headers.join('\r\n')}\r\nContent-Type: text/plain\r\n\r\nBody`,
  );
}
